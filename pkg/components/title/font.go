// font is a 5x7 block font, '#' for on. It covers the letters of the title
// it's drawn with; add glyphs here for another one.
var font = map[rune][7]string{
	'S': {".####", "#....", "#....", ".###.", "....#", "....#", "####."},
	'P': {"####.", "#...#", "#...#", "####.", "#....", "#....", "#...."},
	'E': {"#####", "#....", "#....", "####.", "#....", "#....", "#####"},
	'C': {".####", "#....", "#....", "#....", "#....", "#....", ".####"},
	'H': {"#...#", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"},
	'T': {"#####", "..#..", "..#..", "..#..", "..#..", "..#..", "..#.."},
	'L': {"#....", "#....", "#....", "#....", "#....", "#....", "#####"},
	'A': {".###.", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"},
	'B': {"####.", "#...#", "#...#", "####.", "#...#", "#...#", "####."},
}

// lit reports whether pixel (x, y) of glyph g is on; a letter missing from
// the font is blank.
func lit(g [7]string, x, y int) bool { return x < len(g[y]) && g[y][x] == '#' }
